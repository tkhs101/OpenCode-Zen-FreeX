#!/usr/bin/env bun
// The two machine-readable documents zen-proxy's README links, generated from
// this repository's own: llms.txt is the index a model reads first, and
// llms-full.txt is the whole of the English documentation in one file. Both are
// committed, because a model fetching the repository reads files (or the raw
// host), not a build step, and generating at publish time only in a workflow
// would leave them stale between runs.
//
// `bun run docs:llms` rewrites both from the sources below. The sources are
// README.en.md and MAINTAINING.md, and the index is written here: it is the
// one part that is curated rather than copied, so the words a model is told
// about this project first stay worth reading even as the README moves under
// them.

import { readFile, writeFile } from "node:fs/promises";

const REPO = "tkhs101/OpenCode-Zen-FreeX";

const BASE = `https://github.com/${REPO}`;
const RAW = `https://raw.githubusercontent.com/${REPO}/main`;

const read = (name) => readFile(name, "utf8");

const index = `# OpenCode Zen FreeX

> OpenCode Zen's free models, for hosts that are not OpenCode: a magpie/OpenCode provider plugin that uses the free tier's public credential, discovers new free models automatically, and shapes every request to the OpenCode generation the free tier currently admits (captured headers, system prompt, and the complete tool set, per generation).

## From the repository

- [README (English)](${RAW}/README.en.md): installation, the free-credential login, what each request does, and the full troubleshooting table. The project's own words.
- [MAINTAINING](${RAW}/MAINTAINING.md): why free-tier support is fragile, the capture loop that refreshes the fingerprint ("The loop"), the measured limits Zen under-reports, and every easy way to break the plugin.
- [Machine-readable docs, full](${RAW}/llms-full.txt): the two documents above concatenated, for a context that wants one fetch.
- [The walls snapshot](${RAW}/limits-observed.json): the measured context windows, committed hourly by a workflow and read at run time.
- [The protocol snapshot](${RAW}/models-observed.json): which free model is asked at which endpoint, read from OpenCode's docs table by the same survey.
- [Upstream provider](${BASE}): tkhs101/OpenCode-Zen-FreeX; the plugin this document describes.
- [Predecessor](${BASE}): magpie-community/plugins/packages/zen-free, the plugin this one forked from.
`;

const full = async () => {
  const readme = await read("README.en.md");
  const maintaining = await read("MAINTAINING.md");
  return [
    `# OpenCode Zen FreeX — full documentation (machine-readable)`,
    ``,
    `Generated by make-llms.mjs from README.en.md and MAINTAINING.md on ${new Date().toISOString()}.`,
    `Source: https://github.com/${REPO}`,
    ``,
    `---`,
    ``,
    readme.trimEnd(),
    ``,
    `---`,
    ``,
    maintaining.trimEnd(),
    ``,
  ].join("\n");
};

await writeFile("llms.txt", index, "utf8");
await writeFile("llms-full.txt", await full(), "utf8");
console.log(
  `llms.txt and llms-full.txt written (${index.length} + ${(await read("llms-full.txt")).length} bytes)`,
);
